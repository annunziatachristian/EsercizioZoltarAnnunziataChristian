    private void btnConnettiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConnettiActionPerformed
    String ip = txtIP.getText();
    int porta = 5555;

    try {
        socket = new Socket(ip, porta);
        in = new DataInputStream(socket.getInputStream());
        out = new DataOutputStream(socket.getOutputStream());

        lblStato.setText("CONNESSO");
        lblStato.setForeground(new java.awt.Color(0, 255, 0));

        txtAreaRisposte.append("*** Benvenuto nel tempio di Zoltar ***\n");
        txtAreaRisposte.append("Scegli una personalita' e poi fai la tua domanda.\n\n");

    } catch (IOException e) {
        lblStato.setText("ERRORE CONNESSIONE");
        lblStato.setForeground(new java.awt.Color(255, 80, 80));
        txtAreaRisposte.append("Impossibile collegarsi al server: " + e.getMessage() + "\n");
    }
    }//GEN-LAST:event_btnConnettiActionPerformed

